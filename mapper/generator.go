var defaultTypeMappings []*TypeMapping

func registerDefaultMappings(mapping ...*TypeMapping) {
	defaultTypeMappings = append(defaultTypeMappings, mapping...)
}

func DefaultTypeMappings() []*TypeMapping {
	out := make([]*TypeMapping, len(defaultTypeMappings))
	copy(out, defaultTypeMappings)
	return out
}

func NewGenerator(pkg string, dir string) *Generator {
	gen := &Generator{
		file:             jen.NewFile(pkg),
		dir:              dir,
		pkg:              pkg,
		mappings:         map[string]*TypeMapping{},
		graph:            NewTypeGraph(),
		registeredEnums:  make(map[string]bool),
		usingPkgs:        map[string]*packages.Package{},
		checkedEnumPairs: make(map[string]bool),
	}

	// the exact form `^// Code generated .* DO NOT EDIT\.$` is what go vet, linters
	// and code hosts recognise as a generated file
	gen.file.HeaderComment("Code generated by mapper. DO NOT EDIT.")

	for _, mapper := range defaultTypeMappings {
		gen.AddTypeMapping(mapper)
	}

	return gen
}

type Generator struct {
	file            *jen.File
	dir             string
	srcDir          string // source package directory (for resolving `using:` dependencies)
	pkg             string
	mappings        map[string]*TypeMapping
	graph           *TypeGraph
	registeredEnums map[string]bool
	usingPkgs       map[string]*packages.Package // packages loaded for `using:` references

	strictEnums      bool
	checkedEnumPairs map[string]bool
	enumProblems     []string
}

func (m *Generator) SetSrcDir(dir string) {
	m.srcDir = dir
}

// SetStrictEnums turns enum compatibility problems into errors. By default they
// are only logged, since two enums may legitimately diverge on values that never
// reach the mapper.
func (m *Generator) SetStrictEnums(strict bool) {
	m.strictEnums = strict
}

func (m *Generator) AddTypeMapping(mapping *TypeMapping) {
	name := mapping.types.String()
	m.mappings[name] = mapping
	m.graph.add(mapping)
}

func (m *Generator) GenerateInterface(in *GoInterface) error {
	name := in.Name + "Impl"
	mapperStruct := jen.Type().Id(name).Struct()
	typeCheck := jen.Var().Id("_").Qual(in.Pkg, in.Name).Op("=").Parens(jen.Op("*").Id(name)).Parens(jen.Nil())

	// add type mappings
	for _, method := range in.Methods {
		// only handle cases with one input for now
		if len(method.inputs) == 1 {
			m.AddTypeMapping(&TypeMapping{
				types: TypePair{
					from: method.inputs[0].typ,
					to:   method.output,
				},
				generator: ownMethodConverter(method.name, method.hasError),
				canFail:   method.hasError,
			})
		}

		// discover protobuf enums
		m.discoverEnum(method.output)
		for _, input := range method.inputs {
			m.discoverEnum(input.typ)
		}
	}

	problemsBefore := len(m.enumProblems)

	for _, method := range in.Methods {
		err := m.generateMethod(name, method)
		if err != nil {
			return fmt.Errorf("generating method %s: %w", method.name, err)
		}
	}

	// only populated in strict mode
	if found := m.enumProblems[problemsBefore:]; len(found) > 0 {
		return fmt.Errorf("incompatible enums in %s:\n\t%s", in.Name, strings.Join(found, "\n\t"))
	}

	m.file.Add(mapperStruct)
	m.file.Add(typeCheck)

	return nil
}

// checkEnums verifies that a generated type conversion between two enum-like types
// cannot produce a value the target does not declare. Problems are logged, and in
// strict mode also collected so that generation fails.
func (m *Generator) checkEnums(pair TypePair) {
	key := pair.String()
	if m.checkedEnumPairs[key] {
		return
	}
	m.checkedEnumPairs[key] = true

	problems := checkEnumConversion(pair.from.Raw, pair.to.Raw)
	if len(problems) == 0 {
		return
	}

	for _, problem := range problems {
		message := fmt.Sprintf("enum mismatch converting %s to %s: %s", pair.from, pair.to, problem)

		if m.strictEnums {
			// reported together as a single error once the interface is done
			m.enumProblems = append(m.enumProblems, message)
			continue
		}

		log.Printf("warning: %s", message)
	}
}

func (m *Generator) discoverEnum(typ *GoType) {
	m.discoverEnumWithVisited(typ, make(map[*GoType]bool))
}

func (m *Generator) discoverEnumWithVisited(typ *GoType, visited map[*GoType]bool) {
	if visited[typ] {
		return
	}
	visited[typ] = true

	if typ.IsProtoEnum {
		// use TypeName as key to deduplicate
		key := typ.TypeName
		if !m.registeredEnums[key] {
			registerProtoEnum(m, typ)
			m.registeredEnums[key] = true
		}
	}

	for _, field := range typ.Fields {
		m.discoverEnumWithVisited(field.typ, visited)
	}

	if typ.Element != nil {
		m.discoverEnumWithVisited(typ.Element, visited)
	}
}

func (m *Generator) findField(inputs []*GoParameter, source string) (*GoParameter, GoFieldPath) {
	for _, input := range inputs {

		// see if the input contains our output, otherwise continue
		if inputField := input.typ.findField(source); inputField != nil {
			return input, inputField
		}
	}

	return nil, nil
}

func (m *Generator) buildMapping(f *GoFunction) ([]*ResolvedMapping, error) {
	// look at all the Fields required for the output
	// and try to map them to input Fields

	fields := f.output.Fields
	if f.output.Element != nil {
		fields = f.output.Element.Fields
	}

	var mappings []*ResolvedMapping
	for _, field := range fields {
		source := field.name

		// apply output options
		if options, ok := f.options[field.name]; ok {
			if options.from == "-" {
				continue
			} else if options.from != "" {
				source = options.from
			}

			// handle method: directive — call a named method on the source field value
			if options.method != "" {
				mapping, err := m.buildMethodMapping(f, field, options.method)
				if err != nil {
					return nil, fmt.Errorf("field %s: %w", field.name, err)
				}
				if mapping != nil {
					mappings = append(mappings, mapping)
					continue
				}
			}

			// handle map: directive — switch over explicitly listed values
			if options.mapping != "" {
				mapping, err := m.buildEnumMapping(f, field, options.mapping)
				if err != nil {
					return nil, fmt.Errorf("field %s: %w", field.name, err)
				}
				if mapping != nil {
					mappings = append(mappings, mapping)
					continue
				}
			}

			// handle using directive
			if options.using != "" {
				mapping, err := m.buildUsingMapping(f, field, options.using)
				if err != nil {
					return nil, fmt.Errorf("field %s: %w", field.name, err)
				}
				if mapping != nil {
					mappings = append(mappings, mapping)
					continue
				}
			}
		}

		// resolve the output
		var mapping *ResolvedMapping

		if source == "." {
			// special case of referring directly to the input type
			for _, input := range f.inputs {
				generator, canFail := m.buildGenerator(input.typ, field.typ)

				if generator != nil {
					mapping = &ResolvedMapping{
						output:    field,
						input:     jen.Id(input.name),
						generator: generator,
						canFail:   canFail,
					}
				}
			}

		} else if param, inputField := m.findField(f.inputs, source); inputField != nil {
			// see if the input contains our output, otherwise continue

			generator, canFail := m.buildGenerator(inputField.typ(), field.typ)
			if generator != nil {
				mapping = &ResolvedMapping{
					output:    field,
					input:     jen.Id(param.name).Op(".").Add(inputField.id()),
					generator: generator,
					canFail:   canFail,
				}
			} else {
				log.Printf("Can't convert from type %s to %s", inputField.typ(), field.typ)
			}
		}

		if mapping == nil {
			// If no custom mapper was used and no direct mapping found, try buildGenerator
			for _, input := range f.inputs {
				generator, canFail := m.buildGenerator(input.typ, field.typ)
				if generator != nil {
					mapping = &ResolvedMapping{
						output:    field,
						input:     jen.Id(input.name),
						generator: generator,
						canFail:   canFail,
					}
					break
				}
			}
		}

		if mapping == nil {
			return nil, fmt.Errorf("could not find source for output %s", field.name)
		}

		mappings = append(mappings, mapping)
	}

	return mappings, nil
}

// buildEnumMapping handles // field:F map:"a=X,b=Y" — generates a switch over the
// source value that assigns the listed target value for each listed source value.
// Both sides of a pair may be spelled as a constant name or as the literal value of
// a constant, and the generated code always refers to the constant where one exists.
//
// Go enums are not closed types, a value outside the declared constants is always
// representable, so the switch keeps a default branch that returns an error. That
// makes the mapping fallible and the method therefore has to return an error.
func (m *Generator) buildEnumMapping(f *GoFunction, field *GoField, directive string) (*ResolvedMapping, error) {
	entries, err := parseEnumMap(directive)
	if err != nil {
		return nil, fmt.Errorf("map: %w", err)
	}

	source := field.name
	if opts, ok := f.options[field.name]; ok && opts.from != "" {
		source = opts.from
	}

	param, inputField := m.findField(f.inputs, source)
	if inputField == nil {
		return nil, fmt.Errorf("map: field %q not found in inputs", source)
	}

	srcType := inputField.typ()
	dstType := field.typ

	// the switch runs on the value level, pointers and slices are wrapped below
	srcElem := elementType(srcType)
	dstElem := elementType(dstType)

	if srcType.Kind != dstType.Kind && srcType.Kind != BasicKind && dstType.Kind != BasicKind {
		return nil, fmt.Errorf("map: cannot map %s to %s, the kinds do not line up", srcType, dstType)
	}

	cases := make([]enumSwitchCase, 0, len(entries))
	covered := make(map[string]bool, len(entries))

	for _, entry := range entries {
		fromCode, fromConst, err := m.resolveEnumRef(srcElem, entry.from, "source")
		if err != nil {
			return nil, err
		}

		toCode, _, err := m.resolveEnumRef(dstElem, entry.to, "target")
		if err != nil {
			return nil, err
		}

		if fromConst != "" {
			covered[fromConst] = true
		}

		cases = append(cases, enumSwitchCase{from: fromCode, to: toCode})
	}

	m.checkEnumMapCoverage(srcElem, dstElem, covered)

	gen := enumSwitchMapping(dstElem, field.name, cases)

	switch {
	case srcType.Kind == PointerKind && dstType.Kind == PointerKind:
		gen = mapPointerToPointer(dstElem, gen)
	case srcType.Kind == SliceKind && dstType.Kind == SliceKind:
		gen = sliceMapping(dstElem, gen)
	case srcType.Kind == PointerKind || dstType.Kind == PointerKind ||
		srcType.Kind == SliceKind || dstType.Kind == SliceKind:
		return nil, fmt.Errorf("map: cannot map %s to %s, both sides need to be values, pointers or slices", srcType, dstType)
	}

	return &ResolvedMapping{
		output:    field,
		input:     jen.Id(param.name).Op(".").Add(inputField.id()),
		generator: gen,
		canFail:   true,
	}, nil
}

// resolveEnumRef turns one side of a `map:` pair into the code to emit for it. A
// reference to a constant of the type is emitted as that constant, so the generated
// code stays readable and keeps following the constant if its value ever changes.
// For types that declare no constants the reference is emitted as a literal.
func (m *Generator) resolveEnumRef(typ *GoType, ref string, side string) (jen.Code, string, error) {
	c, found, isEnum := lookupEnumConstant(typ.Raw, ref)
	if found {
		return jen.Qual(typ.Pkg, c.name), c.name, nil
	}

	if isEnum {
		return nil, "", fmt.Errorf("map: %s %q is neither the name nor the value of a constant of %s, declared are: %s",
			side, ref, typ, strings.Join(enumConstantNames(typ.Raw), ", "))
	}

	literal, err := typeLiteral(typ, ref)
	if err != nil {
		return nil, "", fmt.Errorf("map: %s %q: %w", side, ref, err)
	}

	return literal, "", nil
}

// checkEnumMapCoverage reports source constants a `map:` directive does not list.
// The generated switch handles them through its error branch, so this is about
// noticing a value that was forgotten rather than deliberately left out.
func (m *Generator) checkEnumMapCoverage(from, to *GoType, covered map[string]bool) {
	names := enumConstantNames(from.Raw)
	if len(names) == 0 {
		return
	}

	var uncovered []string
	for _, name := range names {
		if !covered[name] {
			uncovered = append(uncovered, name)
		}
	}

	if len(uncovered) == 0 {
		return
	}

	message := fmt.Sprintf("enum mismatch converting %s to %s: not listed in map: %s",
		from, to, strings.Join(uncovered, ", "))

	if m.strictEnums {
		m.enumProblems = append(m.enumProblems, message)
		return
	}

	log.Printf("warning: %s", message)
}

// elementType unwraps a pointer or slice to the type the switch runs on.
func elementType(typ *GoType) *GoType {
	if (typ.Kind == PointerKind || typ.Kind == SliceKind) && typ.Element != nil {
		return typ.Element
	}

	return typ
}

// typeLiteral emits a literal of the given type, used for `map:` references to
// types that declare no constants of their own.
func typeLiteral(typ *GoType, ref string) (jen.Code, error) {
	basic, ok := typ.Raw.Underlying().(*types.Basic)
	if !ok {
		return nil, fmt.Errorf("%s has no constants to refer to", typ)
	}

	var lit jen.Code
	switch {
	case basic.Info()&types.IsString != 0:
		lit = jen.Lit(ref)
	case basic.Info()&types.IsInteger != 0:
		value, err := strconv.ParseInt(ref, 10, 64)
		if err != nil {
			return nil, fmt.Errorf("not a valid integer for %s", typ)
		}
		lit = jen.Lit(int(value))
	default:
		return nil, fmt.Errorf("unsupported type %s, expected a string or integer", typ)
	}

	// an untyped literal is not assignable to a named type, so convert it
	if _, named := typ.Raw.(*types.Named); named {
		return typ.qual().Call(lit), nil
	}

	return lit, nil
}

// buildMethodMapping handles // field:F method:"MethodName" — calls MethodName() on the source
// field and registers the value-level type conversion in the graph so pointer fields can
// automatically derive *T → *U from the same mapping without an explicit annotation.
func (m *Generator) buildMethodMapping(f *GoFunction, field *GoField, methodName string) (*ResolvedMapping, error) {
	source := field.name
	if opts, ok := f.options[field.name]; ok && opts.from != "" {
		source = opts.from
	}

	param, inputField := m.findField(f.inputs, source)
	if inputField == nil {
		return nil, fmt.Errorf("field %q not found in inputs", source)
	}

	srcType := inputField.typ()
	// dereference pointers to find the method
	elemType := srcType
	if elemType.Kind == PointerKind {
		elemType = elemType.Element
	}

	// validate the method exists and has the right signature
	named, ok := elemType.Raw.(*types.Named)
	if !ok {
		return nil, fmt.Errorf("method: %q — source type %s is not a named type", methodName, elemType.Name)
	}
	var method *types.Func
	for i := 0; i < named.NumMethods(); i++ {
		if named.Method(i).Name() == methodName {
			method = named.Method(i)
			break
		}
	}
	if method == nil {
		return nil, fmt.Errorf("method %q not found on type %s", methodName, elemType.Name)
	}
	sig := method.Type().(*types.Signature)
	if sig.Params().Len() != 0 {
		return nil, fmt.Errorf("method %q must take no parameters", methodName)
	}
	if sig.Results().Len() != 1 {
		return nil, fmt.Errorf("method %q must return exactly one value", methodName)
	}

	resultGoType := getGoType(sig.Results().At(0).Type())

	// Register value-level T → U in the type graph so pointer fields (*T → *U) can
	// auto-derive the mapping without needing an explicit annotation.
	m.AddTypeMapping(&TypeMapping{
		types: TypePair{
			from: elemType,
			to:   resultGoType,
		},
		generator: methodConverter(methodName, elemType, false),
	})

	inputExpr := jen.Id(param.name).Op(".").Add(inputField.id())

	// Build the generator: if the source is *T, use nil-safe pointer wrapping.
	var gen GeneratorFunc
	if srcType.Kind == PointerKind && field.typ.Kind == PointerKind {
		inner := methodConverter(methodName, elemType, false)
		gen = mapPointerToPointer(resultGoType, inner)
	} else {
		gen = methodConverter(methodName, elemType, false)
	}

	return &ResolvedMapping{
		output:    field,
		input:     inputExpr,
		generator: gen,
		canFail:   false,
	}, nil
}

// loadUsingPackage loads the package a `using:` reference points at. Loading happens
// from the source dir, so references resolve against the target module's
// dependencies rather than the generator's own module. Results are cached: every
// load is a full type check of the package and its imports, and two references into
// the same package should also come back as the same types.
func (m *Generator) loadUsingPackage(pkgPath string) (*packages.Package, error) {
	if pkg, ok := m.usingPkgs[pkgPath]; ok {
		return pkg, nil
	}

	pkgs, err := packages.Load(&packages.Config{
		Mode: packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
		Dir:  m.srcDir,
	}, pkgPath)
	if err != nil {
		return nil, fmt.Errorf("loading package %q: %w", pkgPath, err)
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("expected one package, got %d", len(pkgs))
	}

	m.usingPkgs[pkgPath] = pkgs[0]

	return pkgs[0], nil
}

func (m *Generator) buildUsingMapping(f *GoFunction, field *GoField, using string) (*ResolvedMapping, error) {
	// parse the function reference
	_, pkgPath, typeName, methodName, _, err := splitPackageAndType(using)
	if err != nil {
		return nil, fmt.Errorf("invalid using reference %q: %w", using, err)
	}

	pkg, err := m.loadUsingPackage(pkgPath)
	if err != nil {
		return nil, err
	}

	var funcSig *types.Signature

	if methodName != "" {
		// method on a type: pkg.(*Type).Method or pkg.(Type).Method
		obj := pkg.Types.Scope().Lookup(typeName)
		if obj == nil {
			return nil, fmt.Errorf("type %q not found in package %q", typeName, pkgPath)
		}
		named, ok := obj.Type().(*types.Named)
		if !ok {
			return nil, fmt.Errorf("%q is not a named type", typeName)
		}

		// find the method
		var method *types.Func
		for i := 0; i < named.NumMethods(); i++ {
			if named.Method(i).Name() == methodName {
				method = named.Method(i)
				break
			}
		}
		if method == nil {
			return nil, fmt.Errorf("method %q not found on type %q", methodName, typeName)
		}
		funcSig = method.Type().(*types.Signature)
	} else {
		// standalone function: pkg.FuncName
		obj := pkg.Types.Scope().Lookup(typeName)
		if obj == nil {
			return nil, fmt.Errorf("function %q not found in package %q", typeName, pkgPath)
		}
		funcObj, ok := obj.(*types.Func)
		if !ok {
			return nil, fmt.Errorf("%q is not a function", typeName)
		}
		funcSig = funcObj.Type().(*types.Signature)
	}

	// validate signature: methods have receiver+0 params; functions have 1 param.
	isMethod := methodName != ""
	if isMethod {
		if funcSig.Params().Len() != 0 {
			return nil, fmt.Errorf("using method must have no parameters (besides receiver), got %d", funcSig.Params().Len())
		}
		if funcSig.Recv() == nil {
			return nil, fmt.Errorf("using method %q has no receiver", methodName)
		}
	} else {
		if funcSig.Params().Len() != 1 {
			return nil, fmt.Errorf("using function must have exactly 1 parameter, got %d", funcSig.Params().Len())
		}
	}
	if funcSig.Results().Len() != 1 && funcSig.Results().Len() != 2 {
		return nil, fmt.Errorf("using function must have 1 or 2 return values, got %d", funcSig.Results().Len())
	}

	hasError := false
	if funcSig.Results().Len() == 2 {
		errType := funcSig.Results().At(1).Type()
		if named, ok := errType.(*types.Named); !ok || named.Obj().Name() != "error" {
			return nil, fmt.Errorf("second return value must be error, got %v", errType)
		}
		hasError = true
	}

	// find an input parameter that matches the function's input type.
	// for methods, the "input type" is the receiver type.
	var funcInputRawType types.Type
	if isMethod {
		funcInputRawType = funcSig.Recv().Type()
	} else {
		funcInputRawType = funcSig.Params().At(0).Type()
	}
	funcInputType := getGoType(funcInputRawType)
	var inputParam *GoParameter
	var inputExpr *jen.Statement
	var sourceFieldType *GoType // actual type of the source field (may differ from funcInputType for pointers)

	// if source is ".", use the whole input
	if f.options[field.name] != nil && f.options[field.name].from == "." {
		// try to find a matching input
		for _, input := range f.inputs {
			if assignableTo(input.typ.Raw, funcInputType.Raw) ||
				(input.typ.Kind == PointerKind && assignableTo(input.typ.Element.Raw, funcInputType.Raw)) {
				inputParam = input
				inputExpr = jen.Id(input.name)
				sourceFieldType = input.typ
				break
			}
		}
	} else {
		// find the field and use it
		source := field.name
		if f.options[field.name] != nil && f.options[field.name].from != "" {
			source = f.options[field.name].from
		}

		if param, inputField := m.findField(f.inputs, source); inputField != nil {
			inputParam = param
			inputExpr = jen.Id(param.name).Op(".").Add(inputField.id())
			sourceFieldType = inputField.typ()
		}
	}

	if inputParam == nil {
		return nil, fmt.Errorf("no input parameter matches the using function's input type %v", funcInputType)
	}

	// create the generator
	var generator GeneratorFunc
	if methodName != "" {
		// method call
		generator = func(ctx *FunctionContext, input jen.Code) jen.Code {
			call := jen.Add(input).Dot(methodName).Call()
			if hasError {
				return ctx.handleError(call)
			}
			return call
		}
	} else {
		// function call
		generator = func(ctx *FunctionContext, input jen.Code) jen.Code {
			call := jen.Qual(pkgPath, typeName).Call(input)
			if hasError {
				return ctx.handleError(call)
			}
			return call
		}
	}

	// If the source field is *T but the function/method expects T, and the target field is *U,
	// wrap with nil-safe pointer-to-pointer logic rather than calling through a raw pointer.
	if sourceFieldType != nil &&
		sourceFieldType.Kind == PointerKind &&
		funcInputType.Kind != PointerKind &&
		field.typ.Kind == PointerKind {
		generator = mapPointerToPointer(field.typ.Element, generator)
	}

	return &ResolvedMapping{
		output:    field,
		input:     inputExpr,
		generator: generator,
		canFail:   hasError,
	}, nil
}

func (m *Generator) buildGenerator(from *GoType, to *GoType) (GeneratorFunc, bool) {
	// build a type pair and see if we can map the fields
	pair := TypePair{
		from: from,
		to:   to,
	}

	// as a special case same types can be assigned without modification
	if types.AssignableTo(pair.from.Raw, pair.to.Raw) {
		return identityMapping, false
	}

	if pair.from.Kind == PointerKind {
		if types.AssignableTo(pair.from.Element.Raw, pair.to.Raw) {
			return mapFromPointer(identityMapping, pair.to), false
		}
	}

	if pair.to.Kind == PointerKind {
		if types.AssignableTo(pair.from.Raw, pair.to.Element.Raw) {
			return mapToPointer(identityMapping), false
		}
	}

	// *T → *U: check before the graph to avoid spurious multi-hop paths through unrelated types.
	// If we can map T → U, derive a nil-safe pointer-to-pointer mapping automatically.
	// A converter that takes *T itself is called directly, it handles nil on its own.
	if from.Kind == PointerKind && to.Kind == PointerKind && !m.graph.hasConverterFrom(pair.from, pair.to) {
		gen, canFail := m.buildGenerator(from.Element, to.Element)
		if gen != nil {
			return mapPointerToPointer(to.Element, gen), canFail
		}
	}

	// otherwise, see if we can map the fields
	mappers := m.graph.getMapping(pair.from, pair.to)
	if mappers != nil {
		gen, canFail := compose(pair, mappers)

		var names []string
		for _, mapper := range mappers {
			names = append(names, fmt.Sprintf("%s:%s", mapper.types.from.Name, mapper.types.to.Name))
		}
		log.Printf("converting %s to %s using %d converters: %s", pair.from.String(), pair.to.String(), len(mappers), strings.Join(names, " -> "))

		return gen, canFail
	}

	// no converter is registered, but the two types may still be a plain Go type
	// conversion away from each other (e.g. two named string types)
	if isDirectConversion(pair.from.Raw, pair.to.Raw) {
		log.Printf("converting %s to %s using a direct type conversion", pair.from.String(), pair.to.String())
		m.checkEnums(pair)
		return convertMapping(pair.to), false
	}

	// if we have no direct match, see if the potential element types can be matched
	if from.Kind == SliceKind && to.Kind == SliceKind {
		gen, canFail := m.buildGenerator(from.Element, to.Element)
		if gen != nil {
			return sliceMapping(to.Element, gen), canFail
		}
	}

	if from.Kind == MapKind && to.Kind == MapKind {
		keyGen, keyCanFail := m.buildGenerator(from.Key, to.Key)
		valueGen, valueCanFail := m.buildGenerator(from.Value, to.Value)
		if keyGen != nil && valueGen != nil {
			return mapMapping(to.Key, to.Value, keyGen, valueGen), keyCanFail || valueCanFail
		}
	}

	if from.Kind == ArrayKind && to.Kind == ArrayKind && arrayLen(from) == arrayLen(to) {
		gen, canFail := m.buildGenerator(from.Element, to.Element)
		if gen != nil {
			return arrayMapping(to, gen), canFail
		}
	}

	// cross-kind conversions (e.g., struct to basic) are not supported
	return nil, false
}

func (m *Generator) generateMethod(mapperName string, f *GoFunction) error {
	to := f.output
	switch {
	case to.Kind == StructKind:
	case to.Kind == PointerKind && to.Element != nil && to.Element.Kind == StructKind:
	default:
		return errors.New("target type must be a struct or a pointer to a struct")
	}

	resolved, err := m.buildMapping(f)
	if err != nil {
		return err
	}

	canFail := false
	for _, r := range resolved {
		if r.canFail {
			canFail = true
			break
		}
	}

	if canFail && !f.hasError {
		return errors.New("at least one converter can fail, function needs to return error")
	} else if !canFail && f.hasError {
		return errors.New("no converter can fail, function can never return error")
	}

	returnType := jen.Empty()
	if to.Kind == PointerKind {
		returnType.Op("*")
	}
	returnType.Qual(to.Pkg, to.Name)

	if f.hasError {
		returnType = jen.Parens(jen.List(returnType, jen.Id("error")))
	}

	var inputTypes []jen.Code
	for i, input := range f.inputs {
		name := input.name
		if name == "" {
			name = fmt.Sprintf("input%d", i)
		}
		inputType := jen.Id(name)

		if input.typ.Kind == PointerKind {
			inputType.Op("*")
		}
		inputType.Qual(input.typ.Pkg, input.typ.Name)

		inputTypes = append(inputTypes, inputType)
	}

	function := jen.Func().Params(jen.Id("m").Id(mapperName)).Id(f.name).Params(jen.List(inputTypes...)).Add(returnType)

	// prepare all the Fields
	body := jen.Empty()
	if len(f.inputs) == 1 && f.inputs[0].typ.Kind == PointerKind {
		body.Add(nilInputReturn(f, to)).Line()
	}
	ctx := &FunctionContext{
		body:       body,
		targetType: f.output,
		canFail:    canFail,
	}

	var assignments []jen.Code
	for _, r := range resolved {
		assignments = append(assignments, jen.Line().Id(r.output.name).Op(":").Add(r.generator(ctx, r.input)))
	}

	assignments = append(assignments, jen.Line())

	// initialize the struct
	returnValue := jen.Empty()
	if to.Kind == PointerKind {
		returnValue.Op("&")
	}

	returnValue.Qual(to.Pkg, to.Name).Values(assignments...)

	if f.hasError {
		returnValue = jen.List(returnValue, jen.Nil())
	}

	function.Block(body, jen.Return(returnValue)).Line()

	m.file.Add(function)

	return nil
}

// nilInputReturn guards a method whose only input is a pointer: nil in gives nil
// out for a pointer result and the zero value for a value result.
func nilInputReturn(f *GoFunction, to *GoType) jen.Code {
	name := f.inputs[0].name
	if name == "" {
		name = "input0"
	}
	var zero jen.Code = jen.Nil()
	if to.Kind != PointerKind {
		zero = jen.Qual(to.Pkg, to.Name).Values()
	}
	if f.hasError {
		zero = jen.List(zero, jen.Nil())
	}
	return jen.If(jen.Id(name).Op("==").Nil()).Block(jen.Return(zero))
}

func (m *Generator) String() (string, error) {
	buf := new(bytes.Buffer)
	err := m.file.Render(buf)
	if err != nil {
		return "", err
	}

	return buf.String(), nil
}

func (m *Generator) Render() error {
	if err := os.MkdirAll(m.dir, 0755); err != nil {
		return fmt.Errorf("creating output directory: %w", err)
	}
	filename := filepath.Join(m.dir, m.pkg+".go")
	return m.file.Save(filename)
}

func compose(pair TypePair, mappings []*TypeMapping) (GeneratorFunc, bool) {
	canFail := false

	for _, mapping := range mappings {
		if mapping.canFail {
			canFail = true
			break
		}
	}

	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		output := input

		outputType := pair.from
		for _, mapping := range mappings {
			inputType := mapping.types.from
			generator := mapping.generator

			if (outputType.Kind == PointerKind) != (inputType.Kind == PointerKind) {
				// need to adjust for pointers

				if inputType.Kind == PointerKind {
					generator = mapToPointer(generator)
				} else {
					generator = mapFromPointer(generator, inputType)
				}
			}

			output = generator(ctx, output)
			outputType = mapping.types.to
		}

		// the last converter in the chain may hand back a pointer where a value was
		// requested (or the other way around), adjust the result to the target type
		if (outputType.Kind == PointerKind) != (pair.to.Kind == PointerKind) {
			if pair.to.Kind == PointerKind {
				output = mapToPointer(identityMapping)(ctx, output)
			} else {
				output = mapFromPointer(identityMapping, pair.to)(ctx, output)
			}
		}

		return output
	}, canFail
}

func mapToPointer(gen GeneratorFunc) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		tmpVar := ctx.tmpVar()

		ctx.add(jen.Id(tmpVar).Op(":=").Add(input).Line())

		return gen(ctx, jen.Op("&").Id(tmpVar))
	}
}

// mapPointerToPointer derives a nil-safe *T → *U mapping from a T → U generator.
// If the input pointer is nil, the output pointer is nil.
func mapPointerToPointer(targetElem *GoType, gen GeneratorFunc) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		outVar := ctx.tmpVar()
		inVar := ctx.tmpVar()

		ctx.add(jen.Var().Id(outVar).Op("*").Add(targetElem.ref()).Line())

		subCtx := &FunctionContext{
			targetType: ctx.targetType,
			body:       jen.Empty(),
			canFail:    false,
			varCounter: ctx.varCounter,
		}
		// inside the nil-check block inVar is *T, while gen expects T. Method calls would
		// auto-dereference, but conversions and plain function calls would not, so
		// dereference into a value first and hand that to the generator.
		derefVar := subCtx.tmpVar()
		subCtx.add(jen.Id(derefVar).Op(":=").Op("*").Id(inVar).Line())

		converted := gen(subCtx, jen.Id(derefVar))
		ctx.varCounter = subCtx.varCounter

		valVar := ctx.tmpVar()
		ifBody := jen.Empty().Add(subCtx.body)
		ifBody.Add(jen.Id(valVar).Op(":=").Add(converted).Line())
		ifBody.Add(jen.Id(outVar).Op("=").Op("&").Id(valVar))

		ctx.add(
			jen.If(
				jen.Id(inVar).Op(":=").Add(input),
				jen.Id(inVar).Op("!=").Nil(),
			).Block(ifBody).Line(),
		)

		return jen.Id(outVar)
	}
}

func mapFromPointer(gen GeneratorFunc, typ *GoType) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		tmpVar := ctx.tmpVar()

		ctx.add(jen.Var().Id(tmpVar).Add(typ.ref()).Line())
		ctx.add(jen.If(input).Op("!=").Nil().Block(
			jen.Id(tmpVar).Op("=").Op("*").Parens(input),
		).Line().Line())

		return gen(ctx, jen.Id(tmpVar))
	}
}

func sliceMapping(targetType *GoType, gen GeneratorFunc) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		tmpVar := ctx.tmpVar()

		initializer := jen.Id(tmpVar).Op(":=").Make(jen.List(jen.Index().Add(targetType.ref()), jen.Len(input)))

		subCtx := &FunctionContext{
			targetType: ctx.targetType,
			body:       jen.Empty(),
			canFail:    false,
			varCounter: ctx.varCounter,
		}

		value := gen(subCtx, jen.Add(input).Index(jen.Id("i")))

		// update parent's varCounter to avoid collisions with temps used in sub-context
		ctx.varCounter = subCtx.varCounter

		loopBody := jen.Id(tmpVar).Index(jen.Id("i")).Op("=").Add(value)
		loop := jen.For(jen.Id("i").Op(":=").Range().Add(input)).Block(subCtx.body.Add(loopBody))

		ctx.add(
			initializer.Line(),
			loop.Line().Line(),
		)

		return jen.Id(tmpVar)
	}
}

func mapMapping(targetKey, targetValue *GoType, keyGen, valueGen GeneratorFunc) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		tmpVar := ctx.tmpVar()

		mapType := jen.Map(jen.Add(targetKey.ref())).Add(targetValue.ref())
		initializer := jen.Id(tmpVar).Op(":=").Make(mapType)

		subCtx := &FunctionContext{
			targetType: ctx.targetType,
			body:       jen.Empty(),
			canFail:    false,
			varCounter: ctx.varCounter,
		}

		convertedKey := keyGen(subCtx, jen.Id("k"))
		convertedValue := valueGen(subCtx, jen.Id("v"))

		// update parent's varCounter to avoid collisions with temps used in sub-context
		ctx.varCounter = subCtx.varCounter

		loopBody := jen.Id(tmpVar).Index(convertedKey).Op("=").Add(convertedValue)
		loop := jen.For(jen.List(jen.Id("k"), jen.Id("v")).Op(":=").Range().Add(input)).Block(subCtx.body.Add(loopBody))

		ctx.add(
			initializer.Line(),
			loop.Line().Line(),
		)

		return jen.Id(tmpVar)
	}
}

// arrayMapping maps every element of a fixed-size array. targetType is the array
// type, not its element: an array cannot be made, and a slice would not be
// assignable to the array field, so the temporary is declared as the array itself.
func arrayMapping(targetType *GoType, gen GeneratorFunc) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		tmpVar := ctx.tmpVar()

		initializer := jen.Var().Id(tmpVar).Add(targetType.ref())

		subCtx := &FunctionContext{
			targetType: ctx.targetType,
			body:       jen.Empty(),
			canFail:    false,
			varCounter: ctx.varCounter,
		}

		value := gen(subCtx, jen.Add(input).Index(jen.Id("i")))

		// update parent's varCounter to avoid collisions with temps used in sub-context
		ctx.varCounter = subCtx.varCounter

		loopBody := jen.Id(tmpVar).Index(jen.Id("i")).Op("=").Add(value)
		loop := jen.For(jen.Id("i").Op(":=").Range().Add(input)).Block(subCtx.body.Add(loopBody))

		ctx.add(
			initializer.Line(),
			loop.Line().Line(),
		)

		return jen.Id(tmpVar)
	}
}

func identityMapping(ctx *FunctionContext, input jen.Code) jen.Code {
	return input
}

// enumSwitchCase is one branch of a generated `map:` switch.
type enumSwitchCase struct {
	from jen.Code
	to   jen.Code
}

// enumSwitchMapping emits a switch over the input that assigns the mapped value for
// every listed case, and returns an error for anything else.
func enumSwitchMapping(target *GoType, fieldName string, cases []enumSwitchCase) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		tmp := ctx.tmpVar()

		ctx.add(jen.Var().Id(tmp).Add(target.ref()).Line())

		ctx.add(jen.Switch(input).BlockFunc(func(group *jen.Group) {
			for _, c := range cases {
				group.Case(c.from).Block(jen.Id(tmp).Op("=").Add(c.to))
			}

			fmtString := jen.Lit(fmt.Sprintf("unmapped value for field %s: %%v", fieldName))
			group.Default().Block(
				jen.Return(ctx.targetType.zero(), jen.Qual("fmt", "Errorf").Call(fmtString, input)),
			)
		}).Line().Line())

		return jen.Id(tmp)
	}
}

// isDirectConversion reports whether `from` can be turned into `to` with a plain Go
// type conversion the generator derives on its own. That is narrower than
// types.ConvertibleTo: types differing only in their name (two distinct
// `type X string`), integers of any width, matching the builtin converters between
// unnamed integers, and string <-> []byte, which changes representation but never
// loses data. Anything else, e.g. int <-> float or string <-> int, needs a converter.
func isDirectConversion(from, to types.Type) bool {
	if from == nil || to == nil {
		return false
	}

	if types.Identical(from, to) {
		// already handled by the assignability check
		return false
	}

	if !types.ConvertibleTo(from, to) {
		return false
	}

	fromU, toU := from.Underlying(), to.Underlying()
	if types.Identical(fromU, toU) {
		return true
	}

	if isInteger(fromU) && isInteger(toU) {
		return true
	}

	return (isString(fromU) && isByteSlice(toU)) || (isByteSlice(fromU) && isString(toU))
}

func isInteger(typ types.Type) bool {
	basic, ok := typ.(*types.Basic)
	return ok && basic.Info()&types.IsInteger != 0
}

func isString(typ types.Type) bool {
	basic, ok := typ.(*types.Basic)
	return ok && basic.Info()&types.IsString != 0
}

func isByteSlice(typ types.Type) bool {
	slice, ok := typ.(*types.Slice)
	if !ok {
		return false
	}
	elem, ok := slice.Elem().Underlying().(*types.Basic)
	return ok && elem.Kind() == types.Uint8
}

// convertMapping emits a plain Go type conversion, e.g. `pkg.Target(input)`.
func convertMapping(to *GoType) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		return to.ref().Call(input)
	}
}

func ownMethodConverter(name string, hasError bool) GeneratorFunc {
	return func(ctx *FunctionContext, input jen.Code) jen.Code {
		call := jen.Id("m").Dot(name).Call(input)

		if hasError {
			return ctx.handleError(call)
		}

		return call
	}
}
